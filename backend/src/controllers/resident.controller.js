const bcrypt = require('bcryptjs');
const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();

/**
 * AUTO-GENERATE EMAIL FROM NAME
 * "Smit Panchal" → "smit@gmail.com"
 * "Rajesh Kumar Patel" → "rajesh@gmail.com"
 * Only first word of name is used.
 * Special chars removed, lowercase.
 */
function generateEmail(name) {
  const firstName = name.trim().split(/\s+/)[0]          // first word
  const clean = firstName.toLowerCase().replace(/[^a-z0-9]/g, '') // only letters/digits
  return `${clean}@gmail.com`
}

/**
 * If generated email already exists, append a number: smit2@gmail.com, smit3@gmail.com ...
 */
async function uniqueEmail(name) {
  const base = generateEmail(name)
  const localPart = base.split('@')[0]

  // Check if base email is free
  const exists = await prisma.user.findUnique({ where: { email: base } })
  if (!exists) return base

  // Try with suffix numbers
  for (let i = 2; i <= 99; i++) {
    const candidate = `${localPart}${i}@gmail.com`
    const taken = await prisma.user.findUnique({ where: { email: candidate } })
    if (!taken) return candidate
  }

  // Fallback: use timestamp
  return `${localPart}${Date.now()}@gmail.com`
}

// GET /api/residents?societyId=...
const listResidents = async (req, res, next) => {
  try {
    const { societyId } = req.query;
    const society = await prisma.society.findFirst({
      where: { id: societyId, adminId: req.user.id }
    });
    if (!society) return res.status(404).json({ error: 'Society not found' });

    const residents = await prisma.resident.findMany({
      where: { house: { societyId } },
      include: {
        house: true,
        user: { select: { id: true, email: true, isActive: true } }
      },
      orderBy: { house: { houseNo: 'asc' } }
    });
    res.json(residents);
  } catch (err) {
    next(err);
  }
};

// POST /api/residents
// email and password are OPTIONAL — auto-generated if not provided
const createResident = async (req, res, next) => {
  try {
    const { name, phone, houseId } = req.body;
    // email/password optional — will be auto-generated
    let { email, password } = req.body;

    // Verify house belongs to admin's society
    const house = await prisma.house.findUnique({
      where: { id: houseId },
      include: { society: true, resident: true }
    });
    if (!house || house.society.adminId !== req.user.id) {
      return res.status(404).json({ error: 'House not found' });
    }
    if (house.resident) {
      return res.status(409).json({ error: 'This house already has a resident' });
    }

    // ── AUTO-GENERATE email if not provided ──────────────────
    if (!email || email.trim() === '') {
      email = await uniqueEmail(name)
    } else {
      email = email.toLowerCase().trim()
      const existing = await prisma.user.findUnique({ where: { email } })
      if (existing) return res.status(409).json({ error: 'Email already registered' })
    }

    // ── AUTO-GENERATE password = house number if not provided ─
    if (!password || password.trim() === '') {
      password = house.houseNo   // e.g. "10", "A-101"
    }

    const passwordHash = await bcrypt.hash(password, 12);

    const user = await prisma.user.create({
      data: { email, passwordHash, role: 'RESIDENT' }
    });

    const resident = await prisma.resident.create({
      data: { name, phone, houseId, userId: user.id },
      include: {
        house: true,
        user: { select: { id: true, email: true } }
      }
    });

    // Return the plain-text password in response so admin can note it
    res.status(201).json({
      ...resident,
      generatedCredentials: {
        email,
        password,          // plain text — shown once to admin
        autoGenerated: !req.body.email && !req.body.password
      }
    });
  } catch (err) {
    next(err);
  }
};

// PUT /api/residents/:id
const updateResident = async (req, res, next) => {
  try {
    const { name, phone, isActive } = req.body;
    const resident = await prisma.resident.findUnique({
      where: { id: req.params.id },
      include: { house: { include: { society: true } } }
    });
    if (!resident || resident.house.society.adminId !== req.user.id) {
      return res.status(404).json({ error: 'Resident not found' });
    }

    const updated = await prisma.resident.update({
      where: { id: req.params.id },
      data: { name, phone },
      include: { house: true, user: { select: { id: true, email: true, isActive: true } } }
    });

    if (typeof isActive === 'boolean') {
      await prisma.user.update({
        where: { id: resident.userId },
        data: { isActive }
      });
    }

    res.json(updated);
  } catch (err) {
    next(err);
  }
};

// DELETE /api/residents/:id
const deleteResident = async (req, res, next) => {
  try {
    const resident = await prisma.resident.findUnique({
      where: { id: req.params.id },
      include: { house: { include: { society: true } } }
    });
    if (!resident || resident.house.society.adminId !== req.user.id) {
      return res.status(404).json({ error: 'Resident not found' });
    }

    await prisma.resident.delete({ where: { id: req.params.id } });
    await prisma.user.delete({ where: { id: resident.userId } });

    res.json({ message: 'Resident and user account removed' });
  } catch (err) {
    next(err);
  }
};

// POST /api/residents/:id/reset-password
const resetPassword = async (req, res, next) => {
  try {
    const { newPassword } = req.body;
    const resident = await prisma.resident.findUnique({
      where: { id: req.params.id },
      include: { house: { include: { society: true } } }
    });
    if (!resident || resident.house.society.adminId !== req.user.id) {
      return res.status(404).json({ error: 'Resident not found' });
    }

    const passwordHash = await bcrypt.hash(newPassword, 12);
    await prisma.user.update({
      where: { id: resident.userId },
      data: { passwordHash }
    });

    res.json({ message: 'Password reset successfully' });
  } catch (err) {
    next(err);
  }
};

module.exports = { listResidents, createResident, updateResident, deleteResident, resetPassword };
